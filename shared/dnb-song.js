export function midiToFreq(m) {
  return 440 * Math.pow(2, (m - 69) / 12);
}

export function mulberry32(seed) {
  let a = seed >>> 0;
  return function () {
    a |= 0;
    a = (a + 0x6d2b79f5) | 0;
    let t = Math.imul(a ^ (a >>> 15), 1 | a);
    t = (t + Math.imul(t ^ (t >>> 7), 61 | t)) ^ t;
    return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
  };
}

export function totalSteps(song = SONG) {
  return song.sections.reduce((sum, s) => sum + s.bars * 16, 0);
}

export function durationSeconds(song = SONG) {
  return (totalSteps(song) * 60) / song.bpm / 4;
}

export function playlistDurationSeconds(songs = SONGS) {
  return songs.reduce((sum, s) => sum + durationSeconds(s), 0);
}
